"""uv run scripts/subset-maple.py --source-dir /path/to/official-v7.9-originals

Use Lumina's UI vocabulary, card examples and error copy. Dynamic prose falls
back to system fonts. No network access or regeneration during app builds.
"""
import argparse
import hashlib
import json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source-dir", type=Path, required=True)
args = parser.parse_args()
out = ROOT / "public/fonts"
sha = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
latin = out / "maple-latin.woff2"
assert sha(latin) == "e7080ef37fa8b3a38f71446e53e546634c27ce2cfe97673478cafc029d6344ee"
latin_font = TTFont(latin)
assert latin_font["name"].getDebugName(5) == "Version 7.900"
assert [(a.axisTag, a.minValue, a.maxValue) for a in latin_font["fvar"].axes] == [("wght", 100, 800)]
latin_points = set(latin_font.getBestCmap())
source_hashes = {
    "Regular": "0fcc5139bfd5ab14ff989bb7dfd5236d0cafc10e60b9828569e6883613ab4085",
    "Medium": "fee9d51498dfcba0921494ac774ad9a374021cf45cfcdf33188ce6421b90c050",
    "SemiBold": "96ed7ae26ee7c50b02b2d2b2bc0f1a0cbabe45ae5d6e6abf6678e2177c415677",
    "Bold": "ca79870485fb382e01f4e70edb08bccd3cf1dbdf74b82023fdf2f0c95db55725",
}
vocabulary, public = set(), set()
inputs = []
for directory in ["app", "components", "constants", "lib", "stores"]:
    for path in sorted((ROOT / directory).rglob("*")):
        if path.suffix not in {".ts", ".tsx"}:
            continue
        chars = set(map(ord, path.read_text()))
        vocabulary |= chars
        inputs.append({"path": str(path.relative_to(ROOT)), "sha256": sha(path)})
        if "(public)" in path.parts or path.name in {"CreditPricing.tsx", "Logo.tsx"}:
            public |= chars
requested = {c for c in vocabulary - latin_points if 0x3000 <= c <= 0x30ff or 0x3400 <= c <= 0x9fff or 0xff00 <= c <= 0xffef}
available = set(TTFont(args.source_dir / "MapleMono-CN-Regular.ttf").getBestCmap())
points = requested & available
groups = {"public": points & public, "app": points - public}

def ranges(codes):
    runs = []
    for c in sorted(codes):
        if runs and c == runs[-1][1] + 1:
            runs[-1][1] = c
        else:
            runs.append([c, c])
    return ",".join(f"U+{a:X}" + (f"-{b:X}" if a != b else "") for a, b in runs)

css = "/* Generated by scripts/subset-maple.py from Lumina source. */\n"
css += f'@font-face {{font-family:"Maple Mono";font-style:normal;font-weight:100 800;font-display:swap;src:url("/fonts/maple-latin.woff2") format("woff2");unicode-range:{ranges(latin_points)};}}\n'
files, sources = {}, {}
for weight, name in [(400, "Regular"), (500, "Medium"), (600, "SemiBold"), (700, "Bold")]:
    source = args.source_dir / f"MapleMono-CN-{name}.ttf"
    assert sha(source) == source_hashes[name], "Use verified official v7.9 originals"
    sources[source.name] = sha(source)
    original = TTFont(source)
    assert original["OS/2"].usWeightClass == weight
    assert original["name"].getDebugName(5) == "Version 7.900"
    assert points <= set(original.getBestCmap())
    for group, codes in groups.items():
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.name_IDs = ["*"]
        options.name_legacy = True
        options.name_languages = ["*"]
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=codes)
        sub.subset(font)
        font.flavor = "woff2"
        filename = f"maple-cn-{group}-{weight}.woff2"
        font.save(out / filename)
        files[filename] = {"bytes": (out / filename).stat().st_size, "sha256": sha(out / filename)}
        css += f'@font-face {{font-family:"Maple Mono CN";font-style:normal;font-weight:{weight};font-display:swap;src:url("/fonts/{filename}") format("woff2");unicode-range:{ranges(codes)};}}\n'
files[latin.name] = {"bytes": latin.stat().st_size, "sha256": sha(latin)}
(ROOT / "app/maple.css").write_text(css)
manifest = {
    "version": "7.900", "fonttools": "4.68.0",
    "latinSource": "https://github.com/subframe7536/maple-font/blob/v7.9/woff2/var/MapleMono%5Bwght%5D-VF.woff2",
    "cnSource": "https://github.com/subframe7536/maple-font/releases/tag/v7.9",
    "cnArchive": "MapleMono-CN-unhinted.zip",
    "sourceSha256": sources, "files": files,
    "publicCodepoints": sorted(groups["public"]), "appCodepoints": sorted(groups["app"]),
    "systemFallbackCodepoints": sorted(requested - available), "vocabularyInputs": inputs,
}
(out / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
print(json.dumps({"publicGlyphs": len(groups["public"]), "appGlyphs": len(groups["app"]), "bytes": sum(f["bytes"] for f in files.values()), "fallback": sorted(requested - available)}))
